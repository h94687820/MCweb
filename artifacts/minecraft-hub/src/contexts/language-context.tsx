export type Translations = (typeof translations)["en"];

interface LanguageContextValue {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: Translations;
  dir: "ltr" | "rtl";
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

const STORAGE_KEY = "modvault-language";

function readStoredLanguage(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored && Object.prototype.hasOwnProperty.call(translations, stored)
      ? (stored as Language)
      : "en";
  } catch {
    return "en";
  }
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(readStoredLanguage);

  const langMeta = LANGUAGES.find((l) => l.id === language)!;

  useEffect(() => {
    document.documentElement.dir = langMeta.dir;
    document.documentElement.lang = language;
  }, [language, langMeta.dir]);

  function setLanguage(lang: Language) {
    if (!Object.prototype.hasOwnProperty.call(translations, lang)) return;
    setLanguageState(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // Keep the current session usable when browser storage is disabled.
    }
  }

  return (
    <LanguageContext.Provider
      value={{ language, setLanguage, t: translations[language] as Translations, dir: langMeta.dir }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}
